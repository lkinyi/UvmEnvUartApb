`define UART0_CLOCK_CYCLE 50
`define UART1_CLOCK_CYCLE 86
//Include the UVM library
`include "uvm_pkg.sv"
`include "uvm_macros.svh"
`include "../uvm_comp/uMacro.svh"
//
//Most TOP module
//
module testTop;
  //Import UVM package
  import uvm_pkg::*;
  //Include all used classes
  `include "../uvm_comp/cApbTransaction.sv"
  `include "../uvm_comp/cApbMasterDriver.sv"
  `include "../uvm_comp/cScoreboard.sv"
  `include "../uvm_comp/cRxFunctionalCoverage.sv"
  `include "../uvm_comp/cRxIrqChecker.sv"
  `include "../uvm_comp/cRxFifoScoreboard.sv"
  `include "../uvm_comp/cApbMasterMonitor.sv"
  `include "../uvm_comp/cApbMasterSequencer.sv"
  `include "../uvm_comp/cApbMasterAgent.sv"
  `include "../uvm_comp/cVSequencer.sv"
  `include "../uvm_comp/cCommonSequence.sv" //Add more common sequences at here 
  `include "../uvm_comp/cVSequence.sv" //Create the TEST PATTERN at here
  `include "../uvm_comp/cRxFifoSequence.sv"
  `include "../uvm_comp/cEnv.sv"
  `include "../uvm_comp/cTest.sv"
  `include "../uvm_comp/cRxFifoTest.sv"
  //Test library generated by scripts/uartvip.py gen: one uvm_test per directory of ../pat
  //Select a test with +UVM_TESTNAME=test_<pattern name>; no source file is copied or modified
  `ifdef PATTERN_LIBRARY
    `include "tests.svh"
  `endif
  //Internal signals
  wire uart_0to1, uart_1to0;
  //Interface declaration
  ifApbMaster vifApbMaster_Tx();
  ifApbMaster vifApbMaster_Rx();
  ifInterrupt vifInterrupt_Tx();
  ifInterrupt vifInterrupt_Rx();
  ifRxFifoProbe rx_probe();
  assign rx_probe.pclk = vifApbMaster_Rx.pclk;
  assign rx_probe.preset_n = vifApbMaster_Rx.preset_n;
  assign rx_probe.serial_rx = uart_0to1;
  assign rx_probe.rx_complete = dut_top.uart_1.receiver.rx_complete;
  assign rx_probe.fifo_we = dut_top.uart_1.receiver.rx_fifo_we;
  assign rx_probe.fifo_re = dut_top.uart_1.receiver.rx_fifo_re;
  assign rx_probe.fifo_empty = dut_top.uart_1.receiver.rx_fifo_empty;
  assign rx_probe.fifo_full = dut_top.uart_1.receiver.rx_fifo_full;
  assign rx_probe.wptr = dut_top.uart_1.receiver.rx_wptr;
  assign rx_probe.rptr = dut_top.uart_1.receiver.rx_rptr;
  assign rx_probe.rx_ne = dut_top.uart_1.rx_ne;
  assign rx_probe.rx_rxf = dut_top.uart_1.rx_rxf;
  assign rx_probe.rx_ov = dut_top.uart_1.rx_ov;
  assign rx_probe.irq = vifInterrupt_Rx.ctrl_if;
  //
  //Clock generator
  //Create 2 asynchronous clock to test
  //
  reg uart0_clk = 1'b0;
  reg uart1_clk = 1'b0;
  always #(`UART0_CLOCK_CYCLE/2) uart0_clk = ~uart0_clk;
  always #(`UART1_CLOCK_CYCLE/2) uart1_clk = ~uart1_clk;
  assign vifApbMaster_Tx.pclk = uart0_clk;
  assign vifApbMaster_Rx.pclk = uart1_clk;
  //
  //Reset generator
  //Only reset one time when starting the simulation
  //
  reg reset_n;
  initial begin
    reset_n = 1'b0;
    #(`UART0_CLOCK_CYCLE + `UART1_CLOCK_CYCLE)
    reset_n = 1'b1;
  end
  assign vifApbMaster_Tx.preset_n = reset_n;
  assign vifApbMaster_Rx.preset_n = reset_n;
  //Checker instances 
  apb_protocol_checker_top apb_protocol_checker_top();
  uart_protocol_checker_top uart_protocol_checker_top();
  // Isolated malformed APB stimulus proves the REAL protocol checker fails a run.
  // It is never connected to a DUT bus and stays idle in ordinary tests.
  logic checker_selftest_trigger = 0;
  apb_protocol_checker checker_selftest();
  assign checker_selftest.pclk = uart0_clk;
  assign checker_selftest.preset_n = reset_n;
  assign checker_selftest.psel = checker_selftest_trigger;
  assign checker_selftest.penable = checker_selftest_trigger;
  assign checker_selftest.pwrite = 0;
  assign checker_selftest.paddr = 0;
  assign checker_selftest.pwdata = 0;
  assign checker_selftest.pstrb = 4'hf;
  assign checker_selftest.prdata = 0;
  assign checker_selftest.pready = 1;
  assign checker_selftest.pslverr = 0;
  initial if ($test$plusargs("PROTOCOL_CHECKER_SELFTEST")) begin
    #500ns; checker_selftest_trigger = 1;
    #150ns; checker_selftest_trigger = 0;
  end
  // Independent malformed UART line: a 200ns pulse inside the START bit.
  // Real source APB configuration is observed, but this line has no DUT driver.
  logic uart_checker_selftest_net = 1;
  uart_protocol_checker uart_checker_selftest();
  assign uart_checker_selftest.pclk = uart0_clk;
  assign uart_checker_selftest.preset_n = reset_n;
  assign uart_checker_selftest.pwrite = vifApbMaster_Tx.pwrite;
  assign uart_checker_selftest.psel = vifApbMaster_Tx.psel;
  assign uart_checker_selftest.penable = vifApbMaster_Tx.penable;
  assign uart_checker_selftest.pready = vifApbMaster_Tx.pready;
  assign uart_checker_selftest.paddr = vifApbMaster_Tx.paddr;
  assign uart_checker_selftest.pwdata = vifApbMaster_Tx.pwdata;
  assign uart_checker_selftest.pstrb = vifApbMaster_Tx.pstrb;
  assign uart_checker_selftest.uart_net = uart_checker_selftest_net;
  initial if ($test$plusargs("UART_CHECKER_SELFTEST")) begin
    #10us; @(negedge uart0_clk); uart_checker_selftest_net = 0;
    #30us; uart_checker_selftest_net = 1;
    #200ns; uart_checker_selftest_net = 0;
    #74600ns;
    for (int i=0;i<8;i++) begin
      uart_checker_selftest_net = 1'(i%2); #104800ns;
    end
    uart_checker_selftest_net = 1;
  end
  //TOP DUT instance
  dut_top dut_top(
     //UART 0 connection
    .pclk_0(vifApbMaster_Tx.pclk),
    .preset_n_0(vifApbMaster_Tx.preset_n),
    .pwrite_0(vifApbMaster_Tx.pwrite),
    .psel_0(vifApbMaster_Tx.psel), 
    .penable_0(vifApbMaster_Tx.penable),
    .paddr_0(vifApbMaster_Tx.paddr),
    .pwdata_0(vifApbMaster_Tx.pwdata),
    .pstrb_0(vifApbMaster_Tx.pstrb), 
    .prdata_0(vifApbMaster_Tx.prdata),
    .pready_0(vifApbMaster_Tx.pready),
    .pslverr_0(vifApbMaster_Tx.pslverr),
    `ifdef INTERRUPT_COM
      .ctrl_if_0(vifInterrupt_Tx.ctrl_if),
    `else
      .ctrl_tif_0(vifInterrupt_Tx.ctrl_tif),
      .ctrl_rif_0(vifInterrupt_Tx.ctrl_rif),
      .ctrl_pif_0(vifInterrupt_Tx.ctrl_pif),
      .ctrl_oif_0(vifInterrupt_Tx.ctrl_oif),
      .ctrl_fif_0(vifInterrupt_Tx.ctrl_fif),
    `endif
    //UART 1 connection
    .pclk_1(vifApbMaster_Rx.pclk),
    .preset_n_1(vifApbMaster_Rx.preset_n),
    .pwrite_1(vifApbMaster_Rx.pwrite),
    .psel_1(vifApbMaster_Rx.psel), 
    .penable_1(vifApbMaster_Rx.penable),
    .paddr_1(vifApbMaster_Rx.paddr),
    .pwdata_1(vifApbMaster_Rx.pwdata),
    .pstrb_1(vifApbMaster_Rx.pstrb), 
    .prdata_1(vifApbMaster_Rx.prdata),
    .pready_1(vifApbMaster_Rx.pready),
    .pslverr_1(vifApbMaster_Rx.pslverr),
    `ifdef INTERRUPT_COM
       .ctrl_if_1(vifInterrupt_Rx.ctrl_if),
    `else
       .ctrl_tif_1(vifInterrupt_Rx.ctrl_tif),
       .ctrl_rif_1(vifInterrupt_Rx.ctrl_rif),
       .ctrl_pif_1(vifInterrupt_Rx.ctrl_pif),
       .ctrl_oif_1(vifInterrupt_Rx.ctrl_oif),
       .ctrl_fif_1(vifInterrupt_Rx.ctrl_fif),
    `endif
    //To UART protocol checker
    .uart_0to1(uart_0to1),
    .uart_1to0(uart_1to0)
  );
  //Interface connection
  //Connect TOP DUT to UVM components
  initial begin
    //Connect APB interface
    uvm_config_db#(virtual ifRxFifoProbe)::set(null,"uvm_test_top.coEnv.coScoreboard","rx_probe",rx_probe);
    uvm_config_db#(virtual ifApbMaster)::set(null,"uvm_test_top.coEnv.coScoreboard","rx_apb",vifApbMaster_Rx);
    uvm_config_db#(virtual interface ifApbMaster)::set(null,"uvm_test_top.coEnv.coApbMasterAgentTx*","vifApbMaster",vifApbMaster_Tx);
    uvm_config_db#(virtual interface ifApbMaster)::set(null,"uvm_test_top.coEnv.coApbMasterAgentRx*","vifApbMaster",vifApbMaster_Rx);
    //Connect Interrupt interface
    uvm_config_db#(virtual interface ifInterrupt)::set(null,"uvm_test_top.coEnv.coApbMasterAgentTx*","vifInterrupt",vifInterrupt_Tx);
    uvm_config_db#(virtual interface ifInterrupt)::set(null,"uvm_test_top.coEnv.coApbMasterAgentRx*","vifInterrupt",vifInterrupt_Rx);
  end
  //Optional waveform: build with --wave (Verilator) to write wave.vcd
  `ifdef WAVE
    initial begin
      $dumpfile("wave.vcd");
      $dumpvars(0, testTop);
    end
  `endif
  //Run the test pattern
  initial begin
    //This method will get the test name from UVM_TESTNAME
    //which is assigned in the RUN command
    run_test();
  end
  
endmodule
